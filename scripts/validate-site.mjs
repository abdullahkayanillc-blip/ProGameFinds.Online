import { readFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";
const root=process.cwd(), errors=[];
const read=p=>readFileSync(resolve(root,p),"utf8");
const check=(ok,msg)=>{if(!ok)errors.push(msg);};
const pages=["index.html","gaming-products.html","guides.html","about.html","how-we-review.html","affiliate-disclosure.html","privacy.html","terms.html","support.html"];
for(const p of pages){
 check(existsSync(resolve(root,p)),"Missing required page: "+p);
 if(!existsSync(resolve(root,p)))continue;
 const h=read(p);
 check(/<html\b[^>]*lang="en"/i.test(h),p+": language missing");
 check(/<title>[^<]+<\/title>/i.test(h),p+": title missing");
 check(/<meta name="description" content="[^"]{30,}">/i.test(h),p+": description missing");
 check(/<link rel="canonical" href="https:\/\/progamefinds\.online/i.test(h),p+": canonical missing");
 check(/name="viewport"/i.test(h),p+": responsive viewport missing");
 check(!/fonts\.googleapis\.com|fonts\.gstatic\.com/i.test(h),p+": remote font dependency");
}
const home=read("index.html"),catalogue=read("gaming-products.html"),disclosure=read("affiliate-disclosure.html");
const register=JSON.parse(read("data/product-verification.json"));
const policy=register.outbound_link_policy||{},tag=policy.associate_tag;
check(/Discover Gaming Gear/.test(home),"Homepage title is not gaming focused");
check(/gaming mice/i.test(home)&&/handheld PC/i.test(home)&&/sim racing/i.test(home),"Homepage missing restored gaming categories");
check(/gaming-3d\.css/.test(home),"3D gaming stylesheet not loaded");
check(/progamefinds-logo-horizontal\.svg/.test(home),"Brand logo asset not loaded");
check((catalogue.match(/class="product-card"/g)||[]).length>=20,"Gaming product candidate catalogue has fewer than 20 cards");
check((catalogue.match(/amazon\.com\/s\?k=/g)||[]).length>=20,"Amazon search links missing");
check(!/amazon\.com\/dp\//i.test(catalogue),"Unverified direct ASIN links are prohibited");
const requiredDisclosure="As an Amazon Associate I earn from qualifying purchases.";
check(disclosure.includes(requiredDisclosure),"Amazon Associates disclosure missing from affiliate disclosure page");
check(catalogue.includes(requiredDisclosure),"Amazon Associates disclosure not visible on catalogue page");
check(policy.special_links_enabled===true,"Amazon Special Links are not marked enabled");
check(policy.affiliate_account_approval==="adult_account_holder_confirmed","Adult account-holder confirmation missing");
check(policy.account_confirmation_date==="2026-11-26","Affiliate account confirmation date missing");
check(typeof tag==="string"&&tag.length>0,"Assigned Associates Tracking ID missing");
const amazonLinks=[...catalogue.matchAll(/href="(https:\/\/www\.amazon\.com\/[^"]+)"/gi)].map(m=>m[1]);
const tracked=amazonLinks.filter(url=>{try{return new URL(url).searchParams.get("tag")===tag;}catch{return false;}});
check(amazonLinks.length===30,"Expected exactly 30 Amazon catalogue links");
check(tracked.length===amazonLinks.length,"Every Amazon catalogue link must carry the assigned tracking ID");
check((catalogue.match(/class="affiliate-link-disclosure">\(affiliate link\)<\/small>/g)||[]).length===amazonLinks.length,"Every Special Link must have an adjacent affiliate label");
check(/target="_blank" rel="noopener noreferrer"/.test(catalogue),"External Amazon search links need safe target attributes");
check(register.status==="gaming_catalogue_restored_retailer_verification_pending","Product register status mismatch");
check(register.candidate_products.length>=20,"Product evidence register missing candidates");
check(register.candidate_products.every(p=>p.status==="candidate_not_verified"&&p.asin===null&&p.retailer_url===null),"Unverified products incorrectly marked verified");
check(read("sitemap.xml").includes("https://progamefinds.online/gaming-products.html"),"Sitemap missing gaming catalogue");
check(read("sitemap.xml").includes("https://progamefinds.online/guides.html"),"Sitemap missing public gaming guides index");
for(const route of ["/gaming-mice.html","/gaming-keyboards.html","/gaming-headsets.html","/gaming-controllers.html","/gaming-chairs-desks.html","/gaming-room-setup.html"])check(read("_redirects").includes(route),"Legacy gaming route missing: "+route);
check(/Sitemap: https:\/\/progamefinds\.online\/sitemap\.xml/.test(read("robots.txt")),"robots sitemap pointer missing");
const headers=read("_headers");
for(const h of ["X-Content-Type-Options","Referrer-Policy","X-Frame-Options","Content-Security-Policy"])check(headers.includes(h),"Security header missing: "+h);
const css=read("assets/gaming-3d.css");
check(css.length<30*1024,"Gaming CSS exceeds 30KB");
check(/prefers-reduced-motion/.test(css),"Reduced motion support missing");
check(/:focus-visible/.test(css),"Visible focus style missing");
if(errors.length){console.error("PROGAMEFINDS GAMING VALIDATION: FAIL");for(const e of errors)console.error("- "+e);process.exit(1);}
console.log("PROGAMEFINDS GAMING VALIDATION: PASS");
console.log("Required pages: "+pages.length+"; product candidates: "+register.candidate_products.length+"; Amazon Special Links: "+amazonLinks.length+"; tracking ID: "+tag+".");
